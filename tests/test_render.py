def test_refresh_all_sources_succeed(monkeypatch, no_env, profile, snap):
    calls = {}

    def fetch_repos(p, token=None, missing=None):
        calls["repos"] = token
        return {"rhuss/cc-spex": {"full_name": "rhuss/cc-spex", "stars": 400, "url": "https://github.com/rhuss/cc-spex"}}, 4000, [
            "more_tools[0]: repository not found or not public, omitted"
        ]

    def fetch_archive(repo, token=None):
        calls["talks"] = (repo, token)
        return ARCHIVE.read_text(encoding="utf-8")

    def fetch_posts(url, n=3):
        calls["posts"] = (url, n)
        return NEW_POSTS

    monkeypatch.setattr(render.github, "fetch_repos", fetch_repos)
    monkeypatch.setattr(render.talks, "fetch_archive", fetch_archive)
    monkeypatch.setattr(render.blog, "fetch_posts", fetch_posts)
    new, warnings = render.refresh(profile, snap, offline=False, token="tok")
    assert calls == {"repos": "tok", "talks": ("ro14nd-talks/archive", "tok"), "posts": ("https://ro14nd.de/index.xml", 3)}
    # Only displayed values are stored: stars in the rounded form the README shows.
    assert new["total_stars"] == "4.0k"
    assert new["repos"] == {"rhuss/cc-spex": {"full_name": "rhuss/cc-spex", "stars": "400", "url": "https://github.com/rhuss/cc-spex"}}
    assert new["posts"] == [p.to_dict() for p in NEW_POSTS]
    assert len(new["talks"]) == 18  # all archive talks, archive order
    assert new["talks"][0]["title"] == "Spec-Driven Development in Practice"
    assert new["talk_years"] == [2019, 2020, 2021, 2023, 2024, 2025, 2026]  # empty 2020 heading included
    assert set(new) == {"repos", "total_stars", "talks", "talk_years", "posts"}
    assert warnings == ["more_tools[0]: repository not found or not public, omitted"]


