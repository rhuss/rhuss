def _chart(out: str) -> tuple[list[int], list[int], str]:
    chart = re.search(r"```mermaid\n(.*?)\n```", section(out, "Talks"), re.DOTALL).group(1)
    x_axis = re.search(r"x-axis \[(.*)\]", chart).group(1)
    bars = re.search(r"bar \[(.*)\]", chart).group(1)
    y_max = re.search(r'y-axis "Talks" 0 --> (\d+)', chart).group(1)
    return [int(y.strip().strip('"')) for y in x_axis.split(",")], [int(n) for n in bars.split(",")], y_max


