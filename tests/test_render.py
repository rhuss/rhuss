def _repo_with_outputs(tmp_path, profile_text):
    (tmp_path / "profile.yaml").write_text(profile_text, encoding="utf-8")
    (tmp_path / "README.md").write_text("old readme\n", encoding="utf-8")
    (tmp_path / "data").mkdir()
    (tmp_path / "data" / "snapshot.json").write_text('{"total_stars": 1}\n', encoding="utf-8")
