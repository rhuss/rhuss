def heading_index(text: str, title: str) -> int:
    m = re.search(rf"^## {re.escape(title)}$", text, re.MULTILINE)
    assert m, f"heading {title!r} not found"
    return m.start()


def section(text: str, title: str) -> str:
    """Body of the '## <title>' section up to the next '## ' heading or the footer rule."""
    start = heading_index(text, title)
    body = text[start:].split("\n", 1)[1]
    m = re.search(r"^(## |---$)", body, re.MULTILINE)
    return body[: m.start()] if m else body


def header(text: str) -> str:
    return text[: heading_index(text, "Current focus")]


def items(body: str) -> list[str]:
    """Top-level list items of a section; continuation lines are joined to their item."""
    result: list[str] = []
    open_item = False
    for line in body.splitlines():
        if line.startswith("- "):
            result.append(line[2:])
            open_item = True
        elif line.startswith("  ") and open_item:
            result[-1] += "\n" + line.strip()
        else:
            open_item = False
    return result


def footer_date(text: str) -> str:
    m = re.search(r"^<sub>Last updated: (\d{4}-\d{2}-\d{2}) · generated by profilegen</sub>$", text, re.MULTILINE)
    assert m, "footer line not found"
    return m.group(1)


