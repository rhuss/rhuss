"""Refresh live data and render README.md (FR-001..FR-010, FR-019).

``refresh`` fetches every live source independently and merges the results
into the snapshot; a failing source keeps its previous snapshot values.
``render_readme`` is a pure function of the profile, the snapshot, the
existing README (for the footer date) and the date of today.

Template lookup: ``<root>/templates/README.md.j2`` when it exists, otherwise
the ``templates/`` directory of this source checkout (two levels above the
package). That lets tests and previews use a scratch ``root`` that only holds
book covers.
"""

from __future__ import annotations

import re
from datetime import date
from pathlib import Path
from urllib.parse import quote, urlsplit

from jinja2 import Environment, FileSystemLoader, StrictUndefined

from profilegen import snapshot as snapshot_mod
from profilegen.model import PROJECT_SECTIONS, ROLE_LABELS, Badge, Profile, Project
from profilegen.sources import blog, github, http, talks
from profilegen.sources.http import NotFound, SourceError

__all__ = ["FOOTER_PREFIX", "refresh", "render_readme", "format_stars", "badge_url", "md_text", "safe_url"]

FOOTER_PREFIX = "<sub>Last updated: "
FOOTER_SUFFIX = " · generated by profilegen</sub>"
TEMPLATE_NAME = "README.md.j2"
UNAVAILABLE = "_Currently unavailable._"
MONTHS = ("Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec")

_PLACEHOLDER = "@@FOOTER-DATE@@"
_FOOTER_RE = re.compile(
    "^" + re.escape(FOOTER_PREFIX) + r"(\d{4}-\d{2}-\d{2})" + re.escape(FOOTER_SUFFIX) + "$", re.MULTILINE
)
_PACKAGE_TEMPLATES = Path(__file__).resolve().parents[2] / "templates"


# --- refresh ---------------------------------------------------------------------


def _attempt(fetch):
    """Run one source fetch: ``(value, None)`` on success, ``(None, error)`` on failure.

    A 404 for a whole source (for example the talks archive) is an outage like
    any other, so NotFound is reported as a SourceError.
    """
    try:
        return fetch(), None
    except NotFound as e:
        return None, SourceError(str(e), url=e.url, status=404)
    except SourceError as e:
        return None, e


def _failure_warning(source: str, has_old: bool, err: Exception, omitted: list[str] = ()) -> str:
    """One warning per failed source; omitted data-file entries are listed by path only (FR-019a)."""
    state = "using last known values" if has_old else "no previous values"
    message = f"{source} unavailable, {state} ({err})"
    if omitted:
        message += f"; omitted entries: {', '.join(omitted)}"
    return message


def _displayed_repos(repos: dict) -> dict:
    """Repository values as the README shows them, so the snapshot changes only with the page."""
    return {key: dict(value, stars=_shown_stars(value["stars"])) for key, value in repos.items()}


def refresh(profile: Profile, snapshot: dict, offline: bool, token=None) -> tuple[dict, list[str]]:
    """Fetch all live sources and merge them into ``snapshot``.

    Returns the new snapshot and the warnings. Offline returns the snapshot
    unchanged. Each source fails on its own: ``fetched`` only receives the
    keys of sources that succeeded, so a failed source keeps its snapshot keys.
    """
    if offline:
        return snapshot, []
    settings = profile.settings
    fetched: dict[str, object] = {}
    warnings: list[str] = []

    confirmed_missing: set[str] = set()
    result, err = _attempt(lambda: github.fetch_repos(profile, token, missing=confirmed_missing))
    if err is None:
        repos, total, repo_warnings = result
        fetched["repos"] = _displayed_repos(repos)
        fetched["total_stars"] = format_stars(total)
        warnings.extend(repo_warnings)
    else:
        old_repos = snapshot.get("repos") if isinstance(snapshot.get("repos"), dict) else None
        if confirmed_missing and old_repos is not None:
            # Keep last known values, except for entries already confirmed gone
            # or not public in this run (FR-011 wins over the FR-019 fallback).
            fetched["repos"] = {k: v for k, v in old_repos.items() if k not in confirmed_missing}
        known = fetched.get("repos", old_repos) or {}
        omitted = [
            f"{section}[{index}]"
            for section in PROJECT_SECTIONS
            for index, project in enumerate(getattr(profile, section))
            if project.repo not in known
        ]
        warnings.append(_failure_warning("GitHub", "repos" in snapshot, err, omitted))

    def fetch_talks() -> tuple[list[dict], list[int]]:
        markdown = talks.fetch_archive(settings.talks_repo, token)
        years = talks.archive_years(markdown)
        if not years:
            raise SourceError("talks archive: no year sections found")
        # Year headings without bullets are valid: zero talks, years present.
        return [t.to_dict() for t in talks.parse_archive(markdown)], years

    # "talks" and "talk_years" are one source unit: both replaced or both kept.
    result, err = _attempt(fetch_talks)
    if err is None:
        fetched["talks"], fetched["talk_years"] = result
    else:
        warnings.append(_failure_warning("talks archive", "talks" in snapshot, err))

    result, err = _attempt(lambda: blog.fetch_posts(http.feed_url(settings.feed_url), settings.posts_shown))
    if err is None:
        fetched["posts"] = [p.to_dict() for p in result]
    else:
        warnings.append(_failure_warning("blog feed", "posts" in snapshot, err))

    return snapshot_mod.merge(snapshot, fetched), warnings


# --- formatting helpers ---------------------------------------------------------------


def format_stars(n: int) -> str:
    """Star count: above 999 with one decimal and ``k`` (1234 -> ``1.2k``)."""
    return f"{n / 1000:.1f}k" if n > 999 else str(n)


def _shown_stars(value: int | str) -> str:
    """A snapshot star value as displayed. Snapshots store the displayed string;
    raw integers from older snapshots are formatted the same way."""
    return value if isinstance(value, str) else format_stars(int(value))


def _badge_part(text: str) -> str:
    return quote(text.replace("-", "--").replace("_", "__"), safe="")


def badge_url(badge: Badge) -> str:
    """shields.io static badge URL; unset ``logo``/``logo_color`` are omitted."""
    url = f"https://img.shields.io/badge/-{_badge_part(badge.label)}-{quote(badge.color, safe='')}?style=flat-square"
    if badge.logo:
        url += f"&logo={quote(badge.logo, safe='')}"
    if badge.logo_color:
        url += f"&logoColor={quote(badge.logo_color, safe='')}"
    return url


# Characters that start Markdown or inline HTML constructs anywhere in a line.
_MD_INLINE = re.compile(r"([\\`*_\[\]<>~])")
# Constructs that only matter at the start of a list item: heading, nested list, quote, ordered list.
_MD_LEADING = re.compile(r"^(#|[-+=>]|\d+(?=[.)]))")
_URL_UNSAFE = re.compile(r"[\s()<>]")


def md_text(text: str) -> str:
    """External text (feed titles, talk titles, venues, link labels) as literal Markdown.

    Whitespace collapses to single spaces, so a value can never end the list item.
    """
    text = _MD_INLINE.sub(r"\\\1", " ".join(str(text).split()))
    m = _MD_LEADING.match(text)
    if m:
        end = m.end()
        text = text[:end] + "\\" + text[end:] if m.group(1)[0].isdigit() else "\\" + text
    return text


def safe_url(url) -> str | None:
    """An external link target if it is an absolute http(s) URL with a host, else None.

    Whitespace, parentheses and angle brackets are percent-encoded, so the URL
    cannot end the Markdown link early.
    """
    if not isinstance(url, str):
        return None
    url = url.strip()
    try:
        parts = urlsplit(url)
        host = parts.hostname
    except ValueError:  # for example "https://[x"
        return None
    if parts.scheme.lower() not in ("http", "https") or not host:
        return None
    return _URL_UNSAFE.sub(lambda m: quote(m.group(0), safe=""), url)


def _link(label: str, url) -> str:
    """``[label](url)`` for a safe URL, otherwise the escaped label as plain text."""
    target = safe_url(url)
    return f"[{md_text(label)}]({target})" if target else md_text(label)


def _talk_date(year: int, month: int | None) -> str:
    return f"{MONTHS[month - 1]} {year}" if month and 1 <= month <= 12 else str(year)


# --- view model -------------------------------------------------------------------------


def _project_view(p: Project, repos: dict) -> dict | None:
    info = repos.get(p.repo)
    if not info:
        return None  # missing or non-public repository: never rendered
    return {
        "name": p.name or info["full_name"].split("/", 1)[1],
        "url": p.url or info["url"],
        "emoji_prefix": f"{p.emoji} " if p.emoji else "",
        "stars": _shown_stars(info["stars"]),
        "description": p.description or "",
        "tagline": p.tagline or "",
        "role": ROLE_LABELS.get(p.role, p.role) if p.role else "",
    }


def _section(entries: list, available: bool) -> dict | None:
    """A page section: ``None`` hides it, empty ``entries`` show the "currently unavailable" note.

    The note is per source (FR-019): it appears only when the section's source
    has no value at all (failed, nothing in the snapshot). A source with values
    shows the entries that have one; with none to show, the section is hidden.
    """
    if not available:
        return {"entries": []}
    return {"entries": entries} if entries else None


def _projects(entries: list[Project], repos: dict | None) -> dict | None:
    if not entries:
        return None  # group not used in profile.yaml
    views = [v for v in (_project_view(p, repos or {}) for p in entries) if v is not None]
    return _section(views, repos is not None)


def _talk_line(t) -> str:
    parts = [_link(t.title, t.url)]
    if t.venue:
        parts.append(md_text(t.venue))
    parts.append(_talk_date(t.year, t.month))
    parts += [_link(e["label"], e["url"]) for e in t.extras]
    return " · ".join(parts)


def _post_line(post: dict) -> str:
    return f"{_link(post['title'], post['url'])} · {post['date']}"


def _view(profile: Profile, snap: dict, root: Path, footer: str) -> dict:
    repos = snap["repos"] if isinstance(snap.get("repos"), dict) else None
    all_talks = talks.talks_from_snapshot(snap.get("talks") or [])
    years = talks.per_year(all_talks, snap.get("talk_years"))

    stats = []
    if "total_stars" in snap:
        stats.append(f"⭐ **{_shown_stars(snap['total_stars'])}** stars")
    if "talks" in snap:
        stats.append(f"🎤 **{len(all_talks)}** talks")
    stats.append(f"📚 **{len(profile.books)}** books")

    feed = urlsplit(profile.settings.feed_url)
    blog_url = f"{feed.scheme}://{feed.netloc}/" if feed.scheme in ("http", "https") and feed.netloc else None

    books = []
    for b in profile.books:
        cover = b.cover if b.cover and (Path(root) / b.cover).is_file() else None
        books.append({"title": b.title, "url": b.url, "description": b.description, "cover": cover})

    return {
        "name": profile.name,
        "intro": profile.intro,
        "links": [f"{link.emoji} [{link.label}]({link.url})" if link.emoji else f"[{link.label}]({link.url})"
                  for link in profile.links],
        "badges": [f"![{b.label}]({badge_url(b)})" for b in profile.badges],
        "stats": stats,
        "main_projects": _projects(profile.main_projects, repos),
        "community": _projects(profile.community, repos),
        "books": books,
        "book_width": f"{100 // len(books)}%" if books else "100%",
        "talks": _section(
            [_talk_line(t) for t in talks.recent(all_talks, profile.settings.talks_shown)], "talks" in snap
        ),
        "chart": {
            "years": [f'"{y}"' for y, _ in years],
            "counts": [c for _, c in years],
            "max": max(1, max(c for _, c in years)),
        } if years and all_talks else None,
        "posts": _section(
            [_post_line(p) for p in (snap.get("posts") or [])[: profile.settings.posts_shown]], "posts" in snap
        ),
        "blog_url": blog_url,
        "blog_host": feed.netloc,
        "more_tools": _projects(profile.more_tools, repos),
        "unavailable": UNAVAILABLE,
        "footer": footer,
    }


# --- rendering -------------------------------------------------------------------------------


def _environment(root: Path) -> Environment:
    local = Path(root) / "templates"
    directory = local if (local / TEMPLATE_NAME).is_file() else _PACKAGE_TEMPLATES
    return Environment(
        loader=FileSystemLoader(str(directory)),
        keep_trailing_newline=True,
        autoescape=False,
        undefined=StrictUndefined,
        trim_blocks=True,
        lstrip_blocks=True,
    )


def _footer(day: str) -> str:
    return f"{FOOTER_PREFIX}{day}{FOOTER_SUFFIX}"


def render_readme(profile: Profile, snapshot: dict, existing_readme: str | None, today: date, root: Path) -> str:
    """Render the README. The footer keeps the date of ``existing_readme`` when
    everything except the footer is unchanged, otherwise it shows ``today``."""
    template = _environment(root).get_template(TEMPLATE_NAME)
    body = template.render(_view(profile, snapshot, Path(root), _footer(_PLACEHOLDER)))

    day = today.isoformat()
    if existing_readme is not None:
        m = _FOOTER_RE.search(existing_readme)
        if m and _FOOTER_RE.sub(_footer(_PLACEHOLDER).replace("\\", "\\\\"), existing_readme) == body:
            day = m.group(1)
    return body.replace(_footer(_PLACEHOLDER), _footer(day))
