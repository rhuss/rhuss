    x_axis = re.search(r"x-axis \[(.*)\]", chart).group(1)
    assert [int(y.strip().strip('"')) for y in x_axis.split(",")] == [2021, 2022, 2023, 2024, 2025, 2026]
    bars = re.search(r"bar \[(.*)\]", chart).group(1)
